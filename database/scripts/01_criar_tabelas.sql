CREATE TABLE usuario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(120)             NOT NULL,
    senha_hash  VARCHAR(100)             NOT NULL,
    perfil      VARCHAR(20)              NOT NULL,
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('FEIRANTE', 'COZINHA'))
);

CREATE TABLE feira (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120)     NOT NULL,
    endereco    VARCHAR(200)     NOT NULL,
    latitude    DOUBLE PRECISION NOT NULL,
    longitude   DOUBLE PRECISION NOT NULL,
    dia_semana  VARCHAR(10)      NOT NULL,
    CONSTRAINT ck_feira_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_feira_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_feira_dia_semana CHECK (dia_semana IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'))
);

CREATE TABLE feirante (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT       NOT NULL,
    feira_id      BIGINT       NOT NULL,
    nome          VARCHAR(120) NOT NULL,
    telefone      VARCHAR(20)  NOT NULL,
    nome_barraca  VARCHAR(120) NOT NULL,
    CONSTRAINT uk_feirante_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_feirante_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_feirante_feira FOREIGN KEY (feira_id) REFERENCES feira (id)
);

CREATE TABLE cozinha (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id           BIGINT           NOT NULL,
    nome                 VARCHAR(120)     NOT NULL,
    responsavel          VARCHAR(120)     NOT NULL,
    telefone             VARCHAR(20)      NOT NULL,
    endereco             VARCHAR(200)     NOT NULL,
    latitude             DOUBLE PRECISION NOT NULL,
    longitude            DOUBLE PRECISION NOT NULL,
    raio_busca_km        DOUBLE PRECISION NOT NULL,
    capacidade_carga_kg  NUMERIC(10, 2)   NOT NULL,
    CONSTRAINT uk_cozinha_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_cozinha_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_cozinha_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_cozinha_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_cozinha_raio CHECK (raio_busca_km > 0),
    CONSTRAINT ck_cozinha_capacidade CHECK (capacidade_carga_kg > 0)
);

CREATE TABLE oferta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feirante_id     BIGINT                   NOT NULL,
    tipo            VARCHAR(20)              NOT NULL,
    descricao       VARCHAR(255)             NOT NULL,
    quantidade_kg   NUMERIC(10, 2)           NOT NULL,
    horario_limite  TIMESTAMP WITH TIME ZONE NOT NULL,
    foto_url        VARCHAR(500),
    status          VARCHAR(20)              NOT NULL,
    criada_em       TIMESTAMP WITH TIME ZONE NOT NULL,
    versao          BIGINT                   NOT NULL DEFAULT 0,
    CONSTRAINT fk_oferta_feirante FOREIGN KEY (feirante_id) REFERENCES feirante (id),
    CONSTRAINT ck_oferta_tipo CHECK (tipo IN ('FRUTA', 'LEGUME', 'VERDURA')),
    CONSTRAINT ck_oferta_status CHECK (status IN ('DISPONIVEL', 'RESERVADA', 'RETIRADA', 'EXPIRADA')),
    CONSTRAINT ck_oferta_quantidade CHECK (quantidade_kg > 0),
    CONSTRAINT ck_oferta_horario CHECK (horario_limite > criada_em)
);

CREATE TABLE reserva (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oferta_id     BIGINT                   NOT NULL,
    cozinha_id    BIGINT                   NOT NULL,
    reservada_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reserva_oferta UNIQUE (oferta_id),
    CONSTRAINT fk_reserva_oferta FOREIGN KEY (oferta_id) REFERENCES oferta (id),
    CONSTRAINT fk_reserva_cozinha FOREIGN KEY (cozinha_id) REFERENCES cozinha (id)
);

CREATE TABLE retirada (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id              BIGINT                   NOT NULL,
    peso_kg                 NUMERIC(10, 2),
    confirmado_feirante_em  TIMESTAMP WITH TIME ZONE,
    confirmado_cozinha_em   TIMESTAMP WITH TIME ZONE,
    concluida_em            TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_retirada_reserva UNIQUE (reserva_id),
    CONSTRAINT fk_retirada_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id),
    CONSTRAINT ck_retirada_peso CHECK (peso_kg IS NULL OR peso_kg > 0)
);

CREATE INDEX ix_feirante_feira ON feirante (feira_id);
CREATE INDEX ix_oferta_feirante ON oferta (feirante_id);
CREATE INDEX ix_oferta_status_horario ON oferta (status, horario_limite);
CREATE INDEX ix_reserva_cozinha ON reserva (cozinha_id);
